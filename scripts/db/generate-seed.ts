/**
 * Generates supabase/seed.sql from lib/cms/seed.ts.
 *   npm run db:seed:generate
 * The SQL is idempotent: `on conflict do nothing` with deterministic IDs means
 * running it again inserts nothing and never overwrites edits made in the CMS.
 */
import { writeFileSync } from "node:fs";
import { seedTables } from "../../lib/cms/seed";

const JSON_COLUMNS = new Set(["content", "settings", "social_links"]);
const ARRAY_COLUMNS = new Set(["points", "categories"]);

function lit(col: string, v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (JSON_COLUMNS.has(col)) return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  if (ARRAY_COLUMNS.has(col)) {
    const arr = v as string[];
    return arr.length ? `array[${arr.map((s) => `'${String(s).replace(/'/g, "''")}'`).join(", ")}]::text[]` : `'{}'::text[]`;
  }
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

const conflict: Record<string, string> = {
  site_settings: "(id)",
  project_milestones: "(project_id, milestone_id)",
};

let sql = `-- ════════════════════════════════════════════════════════════════════
-- VoltageAfrica CMS · seed data (generated by scripts/db/generate-seed.ts)
-- Safe to run more than once: existing rows are left untouched.
-- ════════════════════════════════════════════════════════════════════
begin;
`;

for (const [table, rows] of Object.entries(seedTables)) {
  if (!rows.length) continue;
  const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  sql += `\n-- ${table} (${rows.length})\ninsert into public.${table} (${cols.join(", ")}) values\n`;
  sql += rows
    .map((r) => `  (${cols.map((c) => lit(c, (r as Record<string, unknown>)[c])).join(", ")})`)
    .join(",\n");
  sql += `\non conflict ${conflict[table] ?? "(id)"} do nothing;\n`;
}
sql += "\ncommit;\n";

writeFileSync("supabase/seed.sql", sql);
console.log(`supabase/seed.sql written (${Object.values(seedTables).reduce((n, r) => n + r.length, 0)} rows)`);
